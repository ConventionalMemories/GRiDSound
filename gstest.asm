; ---------- TickSetup (from GRiDBench / GRiD Noid) ----------
; The PROM's refresh counter: it goes up by 16 every screen refresh
; (about 56 a second on a real 1101). TickSetup finds it in the PROM:
;   2E A1 gg gg        MOV AX, CS:tickGranularity
;   01 06 cc cc        ADD sysCounter, AX
;   83 16 cc cc 00     ADC sysCounter+2, 0
;   9A oo oo ss ss     CALL TimerInterrupt
; and, up to 48 bytes before, 2E 8E 1E dd dd (MOV DS, CS:DataFrame).
; FUNCTION TickSetup: INTEGER   1 found, 0 not found
TICKSETUP	PROC	NEAR
		PUSH	SI
		PUSH	DI
		PUSH	ES
		PUSH	DS
		MOV	AX, 0FC00H
		MOV	ES, AX
		XOR	DI, DI
TsLoop:		CMP	WORD PTR ES:[DI], 0A12EH
		JNE	TsNext
		CMP	WORD PTR ES:[DI+4], 0601H
		JNE	TsNext
		CMP	BYTE PTR ES:[DI+8], 83H
		JNE	TsNext
		CMP	BYTE PTR ES:[DI+13], 9AH
		JNE	TsNext
		MOV	SI, DI
		MOV	CX, 48
TsBack:		DEC	SI
		CMP	WORD PTR ES:[SI], 8E2EH
		JNE	TsB2
		CMP	BYTE PTR ES:[SI+2], 1EH
		JE	TsFound
TsB2:		LOOP	TsBack
TsNext:		INC	DI
		CMP	DI, 3FF0H
		JB	TsLoop
		XOR	AX, AX
		JMP	TsDone
TsFound:	MOV	BX, ES:[SI+3]		; DataFrame, in the PROM's code segment
		MOV	AX, ES:[DI+6]		; sysCounter
		MOV	tickOff, AX
		MOV	AX, ES:[DI+16]		; the PROM's code segment
		MOV	DS, AX
		MOV	AX, [BX]		; the PROM's data segment
		MOV	tickSeg, AX
		MOV	AX, 1
TsDone:		POP	DS
		POP	ES
		POP	DI
		POP	SI
		RET
TICKSETUP	ENDP

; FUNCTION SpinFor (refreshes): INTEGER
; Waits for a new refresh, then counts turns of a small loop (about
; 40 clocks a turn) until that many more refreshes have passed. Less
; turns with a background sound running = the CPU time the sound takes.
SPINFOR		PROC	NEAR
		PUSH	BP
		MOV	BP, SP
		PUSH	SI
		PUSH	DI
		PUSH	ES
		MOV	ES, tickSeg
		MOV	BX, tickOff
		MOV	AX, ES:[BX]
SfStart:	CMP	AX, ES:[BX]
		JE	SfStart
		MOV	SI, ES:[BX]		; a refresh just began
		MOV	CX, [BP+4]
		XOR	DI, DI
SfLoop:		INC	DI
		MOV	AX, ES:[BX]
		CMP	AX, SI
		JE	SfLoop
		MOV	SI, AX
		LOOP	SfLoop
		MOV	AX, DI
		POP	ES
		POP	DI
		POP	SI
		POP	BP
		RET	2
SPINFOR		ENDP

